-- Phase 6: additive; does not rewrite existing POS records or stock.
CREATE TABLE IF NOT EXISTS offline_catalogs (
 id UUID PRIMARY KEY, device_id UUID NOT NULL, issued_to INTEGER NOT NULL REFERENCES users(id),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 expires_at TIMESTAMPTZ NOT NULL, snapshot JSONB NOT NULL, policy_hash TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS offline_catalogs_device ON offline_catalogs(device_id,created_at DESC);
CREATE INDEX IF NOT EXISTS offline_catalogs_policy ON offline_catalogs(device_id,policy_hash,expires_at);
CREATE TABLE IF NOT EXISTS offline_sales (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 device_id UUID NOT NULL, client_id UUID NOT NULL, user_id INTEGER NOT NULL REFERENCES users(id),
 catalog_id UUID REFERENCES offline_catalogs(id), payload_hash TEXT NOT NULL, payload JSONB NOT NULL,
 order_id INTEGER UNIQUE REFERENCES orders(id), received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 synced_at TIMESTAMPTZ, status TEXT NOT NULL CHECK(status IN ('review_required','synced')),
 review_note TEXT, reviewed_by INTEGER REFERENCES users(id), reviewed_at TIMESTAMPTZ,
 UNIQUE(device_id,client_id)
);
CREATE INDEX IF NOT EXISTS offline_sales_user ON offline_sales(user_id,received_at DESC);
CREATE TABLE IF NOT EXISTS offline_stock_movements (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 offline_sale_id BIGINT REFERENCES offline_sales(id), kind TEXT NOT NULL CHECK(kind IN ('product','ingredient')),
 entity_id INTEGER NOT NULL, before_quantity NUMERIC(14,2) NOT NULL,
 delta NUMERIC(14,2) NOT NULL, after_quantity NUMERIC(14,2) NOT NULL CHECK(after_quantity>=0),
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CHECK(after_quantity=before_quantity+delta)
);
CREATE TABLE IF NOT EXISTS offline_stock_conflicts (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 offline_sale_id BIGINT NOT NULL REFERENCES offline_sales(id), kind TEXT NOT NULL CHECK(kind IN ('product','ingredient')),
 entity_id INTEGER NOT NULL, entity_name TEXT NOT NULL, requested_quantity NUMERIC(14,2) NOT NULL,
 applied_quantity NUMERIC(14,2) NOT NULL, reason TEXT NOT NULL,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 resolved_at TIMESTAMPTZ, resolved_by INTEGER REFERENCES users(id), resolution_note TEXT,
 counted_quantity NUMERIC(14,2), resolution_movement_id BIGINT REFERENCES offline_stock_movements(id),
 UNIQUE(offline_sale_id,kind,entity_id)
);
CREATE INDEX IF NOT EXISTS offline_conflicts_open ON offline_stock_conflicts(created_at) WHERE resolved_at IS NULL;
CREATE OR REPLACE FUNCTION protect_offline_sale() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP='DELETE' THEN RAISE EXCEPTION 'Offline sales cannot be deleted'; END IF;
 IF OLD.device_id<>NEW.device_id OR OLD.client_id<>NEW.client_id OR OLD.user_id<>NEW.user_id OR
 OLD.payload_hash<>NEW.payload_hash OR OLD.payload<>NEW.payload OR
 (OLD.status='synced' AND (NEW.status<>OLD.status OR NEW.order_id IS DISTINCT FROM OLD.order_id OR NEW.synced_at IS DISTINCT FROM OLD.synced_at))
 THEN RAISE EXCEPTION 'Completed offline sales are immutable'; END IF;
 RETURN NEW;
END; $$;
DROP TRIGGER IF EXISTS protect_offline_sale ON offline_sales;
CREATE TRIGGER protect_offline_sale BEFORE UPDATE OR DELETE ON offline_sales FOR EACH ROW EXECUTE FUNCTION protect_offline_sale();
CREATE OR REPLACE FUNCTION protect_offline_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'Offline audit records are immutable'; END; $$;
DROP TRIGGER IF EXISTS protect_offline_catalog ON offline_catalogs;
CREATE TRIGGER protect_offline_catalog BEFORE UPDATE OR DELETE ON offline_catalogs FOR EACH ROW EXECUTE FUNCTION protect_offline_audit();
DROP TRIGGER IF EXISTS protect_offline_movement ON offline_stock_movements;
CREATE TRIGGER protect_offline_movement BEFORE UPDATE OR DELETE ON offline_stock_movements FOR EACH ROW EXECUTE FUNCTION protect_offline_audit();
