const fs=require('fs'),path=require('path');
process.chdir(path.resolve(__dirname,'../..'));
const dir=path.resolve('database/backups',fs.readdirSync('database/backups').sort().at(-1));
const snapshot=JSON.parse(fs.readFileSync(path.join(dir,'snapshot.json')));
const q=s=>'"'+s.replaceAll('"','""')+'"';
const lit=s=>"'"+String(s).replaceAll("'","''")+"'";
let sql=`-- Generated from verified live MariaDB metadata, not the older seed schema.\n-- Run in a NEW empty PostgreSQL database. Source timestamps were exported in UTC.\nSET TIME ZONE 'UTC';\nCREATE COLLATION snacktime_ci (provider = icu, locale = 'und-u-ks-level1', deterministic = false);\nCREATE EXTENSION IF NOT EXISTS unaccent;\n\n`;
for(const name of Object.keys(snapshot.tables)){
 const cols=snapshot.metadata.COLUMNS.filter(c=>c.TABLE_NAME===name).sort((a,b)=>a.ORDINAL_POSITION-b.ORDINAL_POSITION);
 const defs=cols.map(c=>{
   let type=c.COLUMN_TYPE, checks='';
   if(/^int\(/.test(type))type='integer';
   else if(/^tinyint/.test(type)){type='smallint';checks=` CHECK (${q(c.COLUMN_NAME)} IN (0,1))`;}
   else if(/^decimal/.test(type))type=type.replace('decimal','numeric');
   else if(type==='timestamp')type='timestamptz';
   else if(/^varchar/.test(type))type+=' COLLATE snacktime_ci';
   else if(/^enum\(/.test(type)){checks=` CHECK (${q(c.COLUMN_NAME)} IN ${type.slice(4)})`;type='varchar(30) COLLATE snacktime_ci';}
   else throw Error('Unsupported type: '+type);
   let def='';
   if(c.EXTRA.includes('auto_increment')) def=' GENERATED BY DEFAULT AS IDENTITY';
   else if(c.COLUMN_DEFAULT!==null) def=' DEFAULT '+c.COLUMN_DEFAULT.replace(/current_timestamp\(\)/i,'CURRENT_TIMESTAMP');
   return `  ${q(c.COLUMN_NAME)} ${type}${def}${c.IS_NULLABLE==='NO'?' NOT NULL':''}${checks}`;
 });
 const primary=snapshot.metadata.KEY_COLUMN_USAGE.filter(k=>k.TABLE_NAME===name && k.CONSTRAINT_NAME==='PRIMARY').sort((a,b)=>a.ORDINAL_POSITION-b.ORDINAL_POSITION);
 defs.push('  PRIMARY KEY ('+primary.map(k=>q(k.COLUMN_NAME)).join(', ')+')');
 sql+=`CREATE TABLE ${q(name)} (\n${defs.join(',\n')}\n);\n\n`;
}
for(const name of Object.keys(snapshot.tables)){
 const indexes=Object.groupBy(snapshot.metadata.STATISTICS.filter(i=>i.TABLE_NAME===name && i.INDEX_NAME!=='PRIMARY'),i=>i.INDEX_NAME);
 for(const [index,parts] of Object.entries(indexes)){
   parts.sort((a,b)=>a.SEQ_IN_INDEX-b.SEQ_IN_INDEX);
   if(parts.some(i=>i.SUB_PART!=null || i.INDEX_TYPE!=='BTREE'))throw Error('Review nonstandard index '+index);
   if(Number(parts[0].NON_UNIQUE)===0) sql+=`ALTER TABLE ${q(name)} ADD CONSTRAINT ${q(name+'_'+index)} UNIQUE (${parts.map(i=>q(i.COLUMN_NAME)).join(', ')});\n`;
   else sql+=`CREATE INDEX ${q(name+'_'+index)} ON ${q(name)} (${parts.map(i=>q(i.COLUMN_NAME)).join(', ')});\n`;
 }
}
for(const fk of snapshot.metadata.REFERENTIAL_CONSTRAINTS){
 const keys=snapshot.metadata.KEY_COLUMN_USAGE.filter(k=>k.TABLE_NAME===fk.TABLE_NAME && k.CONSTRAINT_NAME===fk.CONSTRAINT_NAME).sort((a,b)=>a.ORDINAL_POSITION-b.ORDINAL_POSITION);
 sql+=`ALTER TABLE ${q(fk.TABLE_NAME)} ADD CONSTRAINT ${q(fk.CONSTRAINT_NAME)} FOREIGN KEY (${keys.map(k=>q(k.COLUMN_NAME)).join(',')}) REFERENCES ${q(fk.REFERENCED_TABLE_NAME)} (${keys.map(k=>q(k.REFERENCED_COLUMN_NAME)).join(',')}) ON DELETE ${fk.DELETE_RULE} ON UPDATE ${fk.UPDATE_RULE};\n`;
}
sql+=`\nCREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$\nBEGIN\n  IF NEW.updated_at IS NOT DISTINCT FROM OLD.updated_at AND NEW IS DISTINCT FROM OLD THEN NEW.updated_at = CURRENT_TIMESTAMP; END IF;\n  RETURN NEW;\nEND;\n$$;\n`;
for(const c of snapshot.metadata.COLUMNS.filter(c=>c.EXTRA.includes('on update'))){sql+=`CREATE TRIGGER ${q(c.TABLE_NAME+'_updated_at')} BEFORE UPDATE ON ${q(c.TABLE_NAME)} FOR EACH ROW EXECUTE FUNCTION touch_updated_at();\n`;}
fs.writeFileSync('database/schema.postgresql.sql',sql);
console.log('Generated schema for '+Object.keys(snapshot.tables).length+' tables, '+snapshot.metadata.REFERENTIAL_CONSTRAINTS.length+' foreign keys; '+snapshot.metadata.STATISTICS.length+' index columns.');
